/**
 * BLE Revshare contract error codes
 */
export enum BleRevshareErrorCode {
  /** The broadcaster signature is required when providing a broadcaster account */
  BroadcasterSignatureRequired = 6000,
  /** Broadcaster token account is missing but broadcaster is present */
  MissingBroadcasterAccount = 6001,
  /** The computation was aborted */
  AbortedComputation = 6002,
  /** The cluster is not set */
  ClusterNotSet = 6003,
}

/**
 * Get error message for error code
 */
export function getErrorMessage(errorCode: BleRevshareErrorCode): string {
  switch (errorCode) {
    case BleRevshareErrorCode.BroadcasterSignatureRequired:
      return "The broadcaster signature is required when providing a broadcaster account";
    case BleRevshareErrorCode.MissingBroadcasterAccount:
      return "Broadcaster token account is missing but broadcaster is present";
    case BleRevshareErrorCode.AbortedComputation:
      return "The computation was aborted";
    case BleRevshareErrorCode.ClusterNotSet:
      return "The cluster is not set";
    default:
      return "Unknown error";
  }
}

