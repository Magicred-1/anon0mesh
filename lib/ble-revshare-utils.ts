/**
 * Revenue sharing split ratios
 */
export const REVENUE_SHARE = {
  /** Recipient share (70%) */
  RECIPIENT_PERCENTAGE: 70,
  /** Broadcaster share (30%) */
  BROADCASTER_PERCENTAGE: 30,
} as const;

/**
 * Calculate revenue split amounts
 */
export function calculateRevenueSplit(totalAmount: number): {
  recipientAmount: number;
  broadcasterAmount: number;
} {
  const broadcasterAmount = Math.floor(
    (totalAmount * REVENUE_SHARE.BROADCASTER_PERCENTAGE) / 100,
  );
  const recipientAmount = totalAmount - broadcasterAmount;

  return {
    recipientAmount,
    broadcasterAmount,
  };
}

