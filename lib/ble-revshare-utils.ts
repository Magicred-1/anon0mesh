// SERIALIZATION HELPERS
// ============================================

/**
 * Serialize execute_payment instruction data
 */
export function serializeExecutePaymentData(
  params: ExecutePaymentInstructionParams,
): Buffer {
  // Total size: 8 (discriminator) + 8 (offset) + 8 (amount) + 16 (nonce) + 32 (pubKey) = 72 bytes
  const data = Buffer.alloc(72);

  // Discriminator (8 bytes)
  data.set(INSTRUCTION_DISCRIMINATORS.EXECUTE_PAYMENT, 0);

  // Computation offset (8 bytes)
  data.writeBigUInt64LE(BigInt(params.computationOffset.toString()), 8);

  // Amount (8 bytes)
  data.writeBigUInt64LE(BigInt(params.amount.toString()), 16);

  // Nonce (16 bytes / 128 bits)
  const nonceBuffer = Buffer.alloc(16);
  nonceBuffer.writeBigUInt64LE(params.nonce & BigInt("0xFFFFFFFFFFFFFFFF"), 0);
  nonceBuffer.writeBigUInt64LE(params.nonce >> BigInt(64), 8);
  data.set(nonceBuffer, 24);

  // X25519 pub_key (32 bytes)
  data.set(params.pubKey, 40);

  return data;
}

/**
 * Deserialize payment event data
 */
export function deserializePaymentEvent(data: Buffer): PaymentEvent {
  // Event structure:
  // - payer: PublicKey (32 bytes)
  // - recipient: PublicKey (32 bytes)
  // - broadcaster: Option<PublicKey> (1 + 32 bytes)
  // - amount: u64 (8 bytes)
  // - timestamp: i64 (8 bytes)

  let offset = 8; // Skip discriminator

  const payer = new PublicKey(data.subarray(offset, offset + 32));
  offset += 32;

  const recipient = new PublicKey(data.subarray(offset, offset + 32));
  offset += 32;

  // Option<PublicKey> for broadcaster
  const hasBroadcaster = data[offset] === 1;
  offset += 1;
  let broadcaster: PublicKey | null = null;
  if (hasBroadcaster) {
    broadcaster = new PublicKey(data.subarray(offset, offset + 32));
    offset += 32;
  }

  const amount = Number(data.readBigUInt64LE(offset));
  offset += 8;

  const timestamp = Number(data.readBigInt64LE(offset));

  return {
    payer,
    recipient,
    broadcaster,
    amount,
    timestamp,
  };
}

