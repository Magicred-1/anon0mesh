/**
 * Estimate transaction size for payment
 */
export function estimatePaymentTransactionSize(
  hasBroadcaster: boolean,
  hasMemo: boolean,
): number {
  // Base transaction size
  let size = 300; // Approximate base size

  // Payment instruction
  size += 1500; // Approximate instruction size with all accounts

  // Broadcaster adds extra accounts
  if (hasBroadcaster) {
    size += 100; // Additional signature and token account
  }

  // Memo adds extra instruction
  if (hasMemo) {
    size += 100; // Memo instruction
  }

  return size;
}

/**
 * Check if transaction is too large
 */
export function isTransactionTooLarge(size: number): boolean {
  // Solana transaction size limit is 1232 bytes
  return size > 1232;
}

