/**
 * Derive whitelist entry PDA
 */
export function deriveWhitelistEntryPDA(
  mint: PublicKey,
  programId: PublicKey = BLE_REVSHARE_PROGRAM_ID,
): [PublicKey, number] {
  return PublicKey.findProgramAddressSync(
    [Buffer.from("whitelist"), mint.toBuffer()],
    programId,
  );
}

/**
 * Derive Arcium signer PDA
 * This is the PDA used by Arcium for signing on behalf of the program
 */
export function deriveArciumSignerPDA(
  programId: PublicKey = BLE_REVSHARE_PROGRAM_ID,
): [PublicKey, number] {
  return PublicKey.findProgramAddressSync(
    [Buffer.from("ArciumSignerAccount")],
    programId,
  );
}

