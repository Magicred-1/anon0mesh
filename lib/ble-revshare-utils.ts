// VALIDATION HELPERS
// ============================================

/**
 * Validate X25519 public key
 */
export function validateX25519PubKey(pubKey: Uint8Array): boolean {
  return pubKey.length === 32;
}

/**
 * Validate nonce (must be 128 bits)
 */
export function validateNonce(nonce: bigint): boolean {
  return (
    nonce >= BigInt(0) &&
    nonce < BigInt("340282366920938463463374607431768211456")
  );
}

/**
 * Validate computation offset
 */
export function validateComputationOffset(offset: anchor.BN): boolean {
  return offset.gte(new anchor.BN(0));
}

